#!/usr/bin/env bash
# Regenerates ../ABI/GuardedVault.json and a typed ../ABI/GuardedVault.ts from the compiled contract.
set -euo pipefail
cd "$(dirname "$0")"
forge build >/dev/null 2>&1
forge inspect GuardedVault abi --json > ../ABI/GuardedVault.json
printf "// Generated by SmartContracts/export-abi.sh. Do not edit.\nexport const guardedVaultAbi = %s as const;\n" "$(cat ../ABI/GuardedVault.json)" > ../ABI/GuardedVault.ts
echo "wrote ABI/GuardedVault.json and ABI/GuardedVault.ts"
