#!/usr/bin/env bash
# Regenerates ../ABI/<Contract>.json and a typed ../ABI/<Contract>.ts for the vault and its factory.
set -euo pipefail
cd "$(dirname "$0")"
forge build >/dev/null 2>&1
for c in GuardedVault VaultFactory; do
  forge inspect $c abi --json > ../ABI/$c.json
  name="$(tr '[:upper:]' '[:lower:]' <<<"${c:0:1}")${c:1}Abi"
  printf "// Generated by SmartContracts/export-abi.sh. Do not edit.\nexport const %s = %s as const;\n" "$name" "$(cat ../ABI/$c.json)" > ../ABI/$c.ts
  echo "wrote ABI/$c.json and ABI/$c.ts"
done
